/**
 * Did the manager follow the panel, and what happened next?
 *
 * Every suggestion the panel shows is turned into concrete changes (the texts are generated by the panel
 * itself, so they are read back exactly), and every tactic change the plugin recorded is compared with the
 * suggestions that were on screen when it was made. The before/after of the change (tacticChanges.ts) then
 * says how it went; over several matches this shows which rules are worth following.
 */

type Mentality = TacticProfile["mentality"]

export type SuggestedChange =
  | { kind: "team"; id: TeamInstructionId; value: string }
  | { kind: "mentality"; value: Mentality }
  | { kind: "player"; tag: PlayerInstructionTag; add: boolean; playerId: number }
  | { kind: "sub"; offId: number; onId: number }

export type Suggestion = {
  /** Rule family, e.g. "attack.sterile-possession", "opponent.pace", "plan.risk". */
  ruleId: string
  ruleTitle: string
  action: string
  changes: SuggestedChange[]
  /** How strongly the panel backs it (problem > warning > note; plan and opponent weaknesses by their own weight). */
  weight?: number
}

const mentalityOrder: Mentality[] = ["veryDefensive", "defensive", "cautious", "balanced", "positive", "attacking", "veryAttacking"]
const mentalityByLabel = new Map(Object.entries(mentalityLabels).map(([key, label]) => [label, key as Mentality]))
const tagByLabel = new Map(Object.entries(playerInstructionLabels).map(([key, label]) => [label, key as PlayerInstructionTag]))

const escape = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")

/** Every "Instruction: Option" text the panel can write, longest first (so "Muito mais estreita" wins over "Mais estreita"). */
const teamSettings = teamInstructionDefinitions
  .flatMap((definition) =>
    definition.options.map((option) => ({
      id: definition.id,
      value: option.value,
      pattern: new RegExp(`${escape(instructionSetting(definition.id, option.value))}(?=[.,;)]|\\s|$)`),
    }))
  )
  .sort((a, b) => b.pattern.source.length - a.pattern.source.length)

function playerByLabel(match: MatchSnapshot, side: TeamSide, name: string) {
  const squad = match.players.filter((player) => player.team === side)
  return squad.find((player) => playerLabel(player) === name.trim())
}

/** The concrete changes an action text asks for; "keep" advice and conditionals that ask for nothing give none. */
export function parseSuggestion(action: string, match: MatchSnapshot, side: TeamSide): SuggestedChange[] {
  if (/mantém\.?$/.test(action) || action.startsWith("Já tens") || action.startsWith("Mantém")) return []
  const changes: SuggestedChange[] = []

  const mentality = /Mentalidade: [^→]+→ ([^.]+)\./.exec(action) ?? /sobe para ([^.]+)\./.exec(action)
  if (mentality && mentalityByLabel.has(mentality[1].trim())) {
    changes.push({ kind: "mentality", value: mentalityByLabel.get(mentality[1].trim())! })
  }

  const seen = new Set<TeamInstructionId>()
  let rest = action
  for (const setting of teamSettings) {
    if (seen.has(setting.id) || !setting.pattern.test(rest)) continue
    // "Já tens X: mantém" inside a longer text is not a request.
    seen.add(setting.id)
    changes.push({ kind: "team", id: setting.id, value: setting.value })
    rest = rest.replace(setting.pattern, "")
  }

  for (const found of action.matchAll(/(Dar|Tirar) "([^"]+)" (?:a|ao|à) ([^.(:]+?)(?: \(|[.:]|$)/g)) {
    const tag = tagByLabel.get(found[2])
    const player = playerByLabel(match, side, found[3])
    if (tag && player) changes.push({ kind: "player", tag, add: found[1] === "Dar", playerId: player.id })
  }

  // The position label can hold parentheses itself ("MO (D)"), hence the lazy match up to ") → ".
  const sub = /^[^:]+: ([^(]+?) \(.*?\) → ([^.]+)\./.exec(action)
  if (sub) {
    const off = playerByLabel(match, side, sub[1])
    const on = playerByLabel(match, side, sub[2])
    if (off && on) changes.push({ kind: "sub", offId: off.id, onId: on.id })
  }
  return changes
}

/** Rule family of an insight / exploit id: "player.123" → "player", "pace.1.2" → "opponent.pace". */
function ruleOf(id: string, source: "insight" | "opponent" | "plan") {
  if (source === "plan") return `plan.${id}`
  if (source === "opponent") return `opponent.${id.split(".")[0]}`
  return id.startsWith("player.") ? "player" : id
}

/** Everything the panel suggests on screen right now, with the rule behind each action. */
export function collectSuggestions(
  match: MatchSnapshot,
  analysis: MatchAnalysis,
  opponent?: OpponentReport,
  plan?: GamePlan
): Suggestion[] {
  const out: Suggestion[] = []
  const add = (ruleId: string, ruleTitle: string, actions: string[], weight: number) => {
    for (const action of actions) {
      const changes = parseSuggestion(action, match, analysis.side)
      if (changes.length) out.push({ ruleId, ruleTitle, action, changes, weight })
    }
  }
  const toneWeight = { problem: 300, warning: 200, info: 100, good: 50 } as const
  for (const insight of analysis.insights)
    add(ruleOf(insight.id, "insight"), insight.title, insight.actions, toneWeight[insight.tone] + insight.priority)
  for (const exploit of [...(opponent?.exploits ?? []), ...(opponent?.tendencies ?? [])])
    add(ruleOf(exploit.id, "opponent"), exploit.title, exploit.actions, (exploit.tone === "warning" ? 200 : exploit.tone === "good" ? 150 : 60) + exploit.weight)
  // The plan's own decisions (risk, substitutions) weigh most; its other steps repeat rules listed above.
  const planWeight: Record<string, number> = { risk: 400, players: 350 }
  for (const step of plan?.steps ?? [])
    add(ruleOf(step.id, "plan"), `Plano para dar a volta · ${step.title}`, step.actions, planWeight[step.id] ?? 0)
  return out
}

/** What a recorded moment changed, in the same terms as the suggestions. */
export function changesMade(moment: TacticMoment, match: MatchSnapshot, side: TeamSide): SuggestedChange[] {
  const out: SuggestedChange[] = []
  const before = moment.profileBefore
  const after = moment.profileAfter
  if (before && after) {
    if (before.mentality !== after.mentality) out.push({ kind: "mentality", value: after.mentality })
    for (const definition of teamInstructionDefinitions) {
      if (before.team[definition.id] !== after.team[definition.id])
        out.push({ kind: "team", id: definition.id, value: after.team[definition.id] })
    }
  }
  const squad = match.players.filter((player) => player.team === side)
  // Net effect of several clicks on the same instruction (less risk → more → less → default = "remove less risk").
  const net = new Map<string, { name: string; uiKey?: string; from: string | null | undefined; to: string | undefined }>()
  for (const change of moment.changes ?? []) {
    if (change.source !== "ui" || change.kind !== "playerInstruction" || !change.playerName) continue
    const key = `${change.playerName}|${change.uiKey}`
    const entry = net.get(key)
    if (entry) entry.to = change.toLabel
    else net.set(key, { name: change.playerName, uiKey: change.uiKey, from: change.fromLabel, to: change.toLabel })
  }
  for (const { name, uiKey, from, to } of net.values()) {
    const player = findPlayerByGameName(name, squad)
    if (!player || from === to) continue
    const added = playerInstructionTagFor(uiKey, to)
    const removed = playerInstructionTagFor(uiKey, from)
    if (added && added !== removed) out.push({ kind: "player", tag: added, add: true, playerId: player.id })
    if (removed && removed !== added) out.push({ kind: "player", tag: removed, add: false, playerId: player.id })
  }
  // Substitutions made between the moment the change was made and the stoppage it was applied at.
  const from = moment.madeMinute
  const to = moment.minute + 1
  const on = squad.filter((player) => player.status?.subbedOnMinute != null && player.status.subbedOnMinute >= from && player.status.subbedOnMinute <= to)
  for (const player of on) {
    const off = squad.find(
      (candidate) => candidate.status?.subbedOffMinute === player.status?.subbedOnMinute && !out.some((item) => item.kind === "sub" && item.offId === candidate.id)
    )
    if (off) out.push({ kind: "sub", offId: off.id, onId: player.id })
  }
  return out
}

/** Exact, or the same direction for the mentality (asked one level up, went two). */
function matches(suggested: SuggestedChange, made: SuggestedChange, before?: TacticProfile) {
  if (suggested.kind !== made.kind) return false
  switch (suggested.kind) {
    case "team":
      return made.kind === "team" && made.id === suggested.id && made.value === suggested.value
    case "mentality": {
      if (made.kind !== "mentality") return false
      if (made.value === suggested.value) return true
      if (!before) return false
      const start = mentalityOrder.indexOf(before.mentality)
      const want = Math.sign(mentalityOrder.indexOf(suggested.value) - start)
      return want !== 0 && want === Math.sign(mentalityOrder.indexOf(made.value) - start)
    }
    case "player":
      return made.kind === "player" && made.playerId === suggested.playerId && made.tag === suggested.tag && made.add === suggested.add
    case "sub":
      return made.kind === "sub" && made.offId === suggested.offId && made.onId === suggested.onId
  }
}

export type FollowedSuggestion = { ruleId: string; ruleTitle: string; action: string; firstMinute?: number }

/** The suggestions a moment followed (each rule once). */
export function followedSuggestions(
  moment: TacticMoment,
  made: SuggestedChange[],
  suggestions: Array<Suggestion & { firstMinute?: number }>
): FollowedSuggestion[] {
  const out = new Map<string, FollowedSuggestion>()
  for (const suggestion of suggestions) {
    if (out.has(suggestion.ruleId)) continue
    if (suggestion.changes.some((change) => made.some((item) => matches(change, item, moment.profileBefore)))) {
      out.set(suggestion.ruleId, {
        ruleId: suggestion.ruleId,
        ruleTitle: suggestion.ruleTitle,
        action: suggestion.action,
        firstMinute: suggestion.firstMinute,
      })
    }
  }
  return [...out.values()]
}

// ── Live log: suggestions seen while the panel is open ────────────────────

export type LoggedSuggestion = Suggestion & { firstMinute: number; lastMinute: number }

const logKey = "fmmatchlens.analysis.suggestions.v1"
const keptMatches = 20

function changeKey(change: SuggestedChange) {
  switch (change.kind) {
    case "team":
      return `team:${change.id}:${change.value}`
    case "mentality":
      return `mentality:${change.value}`
    case "player":
      return `player:${change.playerId}:${change.tag}:${change.add}`
    case "sub":
      return `sub:${change.offId}:${change.onId}`
  }
}

/** Per match: the suggestions seen and the minutes the panel was open (to tell "not suggested" from "not watched"). */
export type SuggestionLog = { minutes: number[]; entries: LoggedSuggestion[] }

function readLog(): Record<string, SuggestionLog> {
  try {
    const raw = window.localStorage.getItem(logKey)
    return raw ? (JSON.parse(raw) as Record<string, SuggestionLog>) : {}
  } catch {
    return {}
  }
}

const emptyLog = (): SuggestionLog => ({ minutes: [], entries: [] })

/** Adds what is on screen now to the match's log (first and last minute each suggestion was seen). */
export function logSuggestions(matchId: string | undefined, minute: number, suggestions: Suggestion[]): SuggestionLog {
  if (!matchId) return emptyLog()
  const log = readLog()
  const current = log[matchId] ?? emptyLog()
  const byKey = new Map(current.entries.map((entry) => [`${entry.ruleId}|${entry.changes.map(changeKey).join(",")}`, entry]))
  for (const suggestion of suggestions) {
    const key = `${suggestion.ruleId}|${suggestion.changes.map(changeKey).join(",")}`
    const entry = byKey.get(key)
    if (entry) entry.lastMinute = Math.max(entry.lastMinute, minute)
    else byKey.set(key, { ...suggestion, firstMinute: minute, lastMinute: minute })
  }
  const next: SuggestionLog = {
    minutes: current.minutes.includes(minute) ? current.minutes : [...current.minutes, minute],
    entries: [...byKey.values()],
  }
  log[matchId] = next
  const ids = Object.keys(log)
  for (const old of ids.slice(0, Math.max(0, ids.length - keptMatches))) delete log[old]
  try {
    window.localStorage.setItem(logKey, JSON.stringify(log))
  } catch {
    // Storage unavailable: the log lives for this page only.
  }
  return next
}

// A tiny external store, so React reads the log with useSyncExternalStore (stable snapshot per match).
const cache = new Map<string, SuggestionLog>()
const listeners = new Set<() => void>()
const noLog = emptyLog()

export function subscribeSuggestionLog(listener: () => void) {
  listeners.add(listener)
  return () => listeners.delete(listener)
}

export function loggedSuggestions(matchId: string | undefined): SuggestionLog {
  if (!matchId) return noLog
  let entry = cache.get(matchId)
  if (!entry) {
    entry = readLog()[matchId] ?? noLog
    cache.set(matchId, entry)
  }
  return entry
}

/** Records what is on screen and notifies the readers. */
export function recordSuggestions(matchId: string | undefined, minute: number, suggestions: Suggestion[]) {
  if (!matchId) return
  cache.set(matchId, logSuggestions(matchId, minute, suggestions))
  for (const listener of listeners) listener()
}

/** Whether the panel was open in the minutes before a change was made. */
export function watchedAt(log: SuggestionLog, madeMinute: number) {
  return log.minutes.some((minute) => minute <= madeMinute && minute >= madeMinute - 2)
}

/** Logged suggestions on screen when a change was made (seen at or before it, and still within 3 minutes). */
export function suggestionsAt(log: SuggestionLog, madeMinute: number) {
  return log.entries.filter((entry) => entry.firstMinute <= madeMinute && entry.lastMinute >= madeMinute - 3)
}

// ── Outcomes over several matches ─────────────────────────────────────────

export type SuggestionOutcome = {
  ruleId: string
  ruleTitle: string
  action: string
  minute: number
  comparison?: TacticComparison
}

export type RuleEffect = {
  ruleId: string
  ruleTitle: string
  followed: number
  /** Followed with both sides of the comparison long enough (8+ minutes). */
  measured: number
  /** Mean change per 90 minutes after following it (measured ones only). */
  xgFor?: number
  xgAgainst?: number
  examples: SuggestionOutcome[]
}

function rowDelta(comparison: TacticComparison | undefined, label: string) {
  const row = comparison?.rows.find((item) => item.label === label)
  return row ? row.after - row.before : undefined
}

export function ruleEffects(outcomes: SuggestionOutcome[]): RuleEffect[] {
  const byRule = new Map<string, SuggestionOutcome[]>()
  for (const outcome of outcomes) byRule.set(outcome.ruleId, [...(byRule.get(outcome.ruleId) ?? []), outcome])
  const average = (values: Array<number | undefined>) => {
    const present = values.filter((value): value is number => value != null)
    return present.length ? present.reduce((sum, value) => sum + value, 0) / present.length : undefined
  }
  return [...byRule.entries()]
    .map(([ruleId, items]) => {
      const measured = items.filter((item) => item.comparison?.reliable && item.comparison.mode === "beforeAfter")
      return {
        ruleId,
        ruleTitle: items[0].ruleTitle,
        followed: items.length,
        measured: measured.length,
        xgFor: average(measured.map((item) => rowDelta(item.comparison, "xG por 90'"))),
        xgAgainst: average(measured.map((item) => rowDelta(item.comparison, "xG sofrido por 90'"))),
        examples: items,
      }
    })
    .sort((a, b) => b.followed - a.followed)
}

// ── Replaying an archive ──────────────────────────────────────────────────

/**
 * The tactic in force at a moment of the match: the starting tactic, the changes detected so far and the
 * individual instructions read from the players' panels (as the panel does live).
 */
export function effectiveProfileAt(
  profile: TacticProfile,
  normalized: readonly TacticChange[],
  raw: readonly TacticChange[],
  match: MatchSnapshot
): TacticProfile {
  const withChanges = applyTacticChanges(profile, changesUpTo(normalized, match))
  const side = managedSide(match)
  return applyObservedPlayerInstructions(
    withChanges,
    observedPlayerInstructions(changesUpTo(raw, match)),
    match.players.filter((player) => player.team === side)
  )
}

/** Everything the panel would suggest at this moment (whole match so far, like the plan and the opponent tab). */
export function suggestionsFor(match: MatchSnapshot, profile: TacticProfile): Suggestion[] {
  const analysis = analyseMatch(match, profile, { window: fullMatchWindow(match) })
  const opponent = opponentReport(match, analysis.side, profile, analysis.metrics, analysis.opponent)
  const plan = comebackPlan(match, profile, analysis, opponent, teamPerformance(match, analysis.side))
  return collectSuggestions(match, analysis, opponent, plan)
}

/**
 * For an archive with recorded tactic changes: the suggestions on screen at each change (rebuilt by
 * stepping the replay to the minute it was made) and the outcome of the ones that were followed.
 *
 * snapshotAtTick must be called with increasing ticks (replays only move forward); finalSnapshot
 * gives the end of the match, for the before/after comparison.
 */
export function archiveSuggestionOutcomes(
  raw: readonly TacticChange[],
  profile: TacticProfile,
  snapshotAtTick: (tick: number) => MatchSnapshot,
  finalSnapshot: () => MatchSnapshot
): SuggestionOutcome[] {
  const normalized = normalizeTacticChanges(raw)
  const made = normalized.filter((change) => !change.initial && !change.cancelled)
  if (!made.length) return []
  const byMinute = new Map<number, Suggestion[]>()
  for (const change of [...made].sort((a, b) => a.tick - b.tick)) {
    const snapshot = snapshotAtTick(change.tick)
    const minute = snapshot.clock.minute
    if (byMinute.has(minute)) continue
    // The tactic just before the change: what the panel showed while the manager decided.
    const earlier = (item: TacticChange) => item.initial || item.displayTick < change.displayTick
    const before = effectiveProfileAt(profile, normalized.filter(earlier), raw.filter(earlier), snapshot)
    byMinute.set(minute, suggestionsFor(snapshot, before))
  }
  const end = finalSnapshot()
  const side = managedSide(end)
  const report = tacticChangesReport(end, side, profile, normalized)
  const outcomes: SuggestionOutcome[] = []
  for (const moment of report.moments) {
    if (moment.pending) continue
    const suggestions = byMinute.get(moment.madeMinute) ?? []
    for (const item of followedSuggestions(moment, changesMade(moment, end, side), suggestions)) {
      outcomes.push({ ...item, minute: moment.madeMinute, comparison: moment.comparison })
    }
  }
  return outcomes
}

// ── One answer per instruction ────────────────────────────────────────────

/** A change the panel suggests, with every rule that asks for it. */
export type ConsolidatedChange = {
  key: string
  label: string
  change: SuggestedChange
  weight: number
  sources: Array<{ ruleId: string; ruleTitle: string; action: string }>
}

export type Consolidation = {
  /** One change per instruction / player instruction / substitution, strongest first. */
  changes: ConsolidatedChange[]
  /** Changes that lost against a stronger one asking for the opposite. */
  rejected: Array<ConsolidatedChange & { lostTo: ConsolidatedChange }>
  /** Action text → note shown under it where it appears (duplicate or contradicted elsewhere). */
  notes: Map<string, string>
}

/** Opposite individual instructions are one decision ("Fintar mais" vs "Fintar menos"). */
const tagFamilies: Array<PlayerInstructionTag[]> = [
  ["dribbleMore", "dribbleLess"],
  ["shootMore", "shootLess"],
  ["moreRisk", "lessRisk"],
  ["moreForwardRuns", "fewerForwardRuns"],
  ["pressMore", "pressLess"],
  ["stayNarrower", "stayWider"],
]

function decisionOf(change: SuggestedChange) {
  switch (change.kind) {
    case "team":
      return `team:${change.id}`
    case "mentality":
      return "mentality"
    case "player": {
      const family = tagFamilies.find((tags) => tags.includes(change.tag))
      return `player:${change.playerId}:${family ? family.join("|") : change.tag}`
    }
    case "sub":
      return `sub:${change.offId}`
  }
}

function labelOf(change: SuggestedChange, match: MatchSnapshot) {
  const name = (id: number) => {
    const player = match.players.find((candidate) => candidate.id === id)
    return player ? playerLabel(player) : "?"
  }
  switch (change.kind) {
    case "team":
      return instructionSetting(change.id, change.value)
    case "mentality":
      return `Mentalidade: ${mentalityLabels[change.value]}`
    case "player":
      return `${change.add ? "Dar" : "Tirar"} "${playerInstructionLabels[change.tag]}" a ${name(change.playerId)}`
    case "sub":
      return `Substituir ${name(change.offId)} por ${name(change.onId)}`
  }
}

/**
 * Merges the same change asked by several rules and settles contradictions (two values for one instruction,
 * opposite individual instructions, two replacements for one player): the strongest backing wins, the other
 * is kept as a rejected alternative with the reason.
 */
/**
 * Changes that lower the risk the team takes. When losing in the last 20 minutes the comeback plan asks for
 * more risk, so these lose against it even when another rule backs them.
 */
const lowerRisk: Partial<Record<TeamInstructionId, string[]>> = {
  defensiveLine: ["muchLower", "lower", "balanced"],
  defensiveTransition: ["regroup", "balanced"],
  lineOfEngagement: ["lowBlock", "midBlock"],
  timeWasting: ["moreOften"],
  tempo: ["muchLower", "lower"],
  attackingTransition: ["holdShape"],
}

function lowersRisk(change: SuggestedChange) {
  return change.kind === "team" && (lowerRisk[change.id]?.includes(change.value) ?? false)
}

export function consolidateSuggestions(
  suggestions: Suggestion[],
  match: MatchSnapshot,
  options: { chasingLate?: boolean } = {}
): Consolidation {
  const byKey = new Map<string, ConsolidatedChange>()
  for (const suggestion of suggestions) {
    for (const change of suggestion.changes) {
      const key = changeKey(change)
      const entry = byKey.get(key) ?? { key, label: labelOf(change, match), change, weight: 0, sources: [] }
      entry.weight = Math.max(entry.weight, suggestion.weight ?? 0)
      if (!entry.sources.some((source) => source.ruleId === suggestion.ruleId))
        entry.sources.push({ ruleId: suggestion.ruleId, ruleTitle: suggestion.ruleTitle, action: suggestion.action })
      byKey.set(key, entry)
    }
  }
  const decisions = new Map<string, ConsolidatedChange[]>()
  for (const entry of byKey.values()) {
    const decision = decisionOf(entry.change)
    decisions.set(decision, [...(decisions.get(decision) ?? []), entry])
  }
  const changes: ConsolidatedChange[] = []
  const rejected: Consolidation["rejected"] = []
  const notes = new Map<string, string>()
  // Losing late: the plan's call for risk wins over caution asked by other rules.
  const riskCall = options.chasingLate
    ? [...byKey.values()].find((entry) => entry.change.kind === "mentality" && entry.sources.some((source) => source.ruleId === "plan.risk"))
    : undefined
  for (const [decision, entries] of [...decisions]) {
    if (!riskCall) break
    const cautious = entries.filter((entry) => lowersRisk(entry.change))
    for (const entry of cautious) {
      rejected.push({ ...entry, lostTo: riskCall })
      for (const source of entry.sources)
        notes.set(source.action, `A perder na reta final, o plano dá prioridade ao risco ("${riskCall.label}"): fica para depois de empatar.`)
    }
    const kept = entries.filter((entry) => !cautious.includes(entry))
    if (kept.length) decisions.set(decision, kept)
    else decisions.delete(decision)
  }
  for (const options of decisions.values()) {
    // Strongest backing first; with equal weight, the one more rules agree on.
    const [winner, ...losers] = [...options].sort((a, b) => b.weight - a.weight || b.sources.length - a.sources.length)
    changes.push(winner)
    for (const loser of losers) {
      rejected.push({ ...loser, lostTo: winner })
      for (const source of loser.sources)
        notes.set(source.action, `Em conflito com "${winner.label}" (${winner.sources[0].ruleTitle}), que o painel recomenda.`)
    }
    if (winner.sources.length > 1) {
      for (const source of winner.sources) {
        const others = winner.sources.filter((item) => item.ruleId !== source.ruleId).map((item) => item.ruleTitle)
        if (!notes.has(source.action)) notes.set(source.action, `Também sugerido por: ${others.join("; ")}.`)
      }
    }
  }
  changes.sort((a, b) => b.weight - a.weight)
  return { changes, rejected, notes }
}
